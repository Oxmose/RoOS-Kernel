;-------------------------------------------------------------------------------
; EXPORTED FUNCTIONS
;-------------------------------------------------------------------------------
global SpinlockAcquire
global SpinlockRelease
global CPUMemoryFenceRelease
global CPUMemoryFenceAcquire

;-------------------------------------------------------------------------------
; EXPORTED DATA
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; CODE
;-------------------------------------------------------------------------------
section .text
align 4

;-------------------------------------------------------------------------------
; Lock Spinlock
;
; Param:
;     Input: rdi: Address of the lock

SpinlockAcquire:
  lock bts dword [rdi], 0
  jc   __pauseSpinlockPause
  ret

__pauseSpinlockPause:
  pause
  test  dword [rdi], 1
  jnz   __pauseSpinlockPause
  jmp   SpinlockAcquire

;-------------------------------------------------------------------------------
; Unlock Spinlock
;
; Param:
;     Input: rdi: Address of the lock

SpinlockRelease:
  ; Ensure prior memory operations are globally visible before releasing
  ; the lock. This provides the required release semantics on x86.
  mfence
  mov  dword [rdi], 0
  ret

;-------------------------------------------------------------------------------
; CPU Memory acquire fence
;
; Param:
;     None
CPUMemoryFenceAcquire:
  mfence
  ret

;-------------------------------------------------------------------------------
; CPU Memory release fence
;
; Param:
;     None
CPUMemoryFenceRelease:
  mfence
  ret

