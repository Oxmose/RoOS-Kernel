; User entry point.
; Heap is initialized.
; BSS is initialized (zeroed).
; Call main
;-------------------------------------------------------------------------------

;-------------------------------------------------------------------------------
; INCLUDES
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; ARCH
;-------------------------------------------------------------------------------
[bits 64]

;-------------------------------------------------------------------------------
; DEFINES
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; MACRO DEFINE
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; EXTERN DATA
;-------------------------------------------------------------------------------
extern _USER_START_BSS_ADDR
extern _USER_END_BSS_ADDR

;-------------------------------------------------------------------------------
; EXTERN FUNCTIONS
;-------------------------------------------------------------------------------
extern main
extern Syscall

;-------------------------------------------------------------------------------
; EXPORTED FUNCTIONS
;-------------------------------------------------------------------------------
global __user_entry

;-------------------------------------------------------------------------------
; EXPORTED DATA
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; CODE
;-------------------------------------------------------------------------------

section .init
align 4
__user_entry:
    ; Align stack
    and rsp, 0xFFFFFFFFFFFFFFF0

    ; Init BSS
    call _userBSSInit

    ; Call main
    call main

    ; Exit thread
    mov rdi, 3 ; TODO: Update this value with the correct one
    mov rsi, rax
    call Syscall
;-------------------------------------------------------------------------------
; Initializes the user BSS section.
;
; Param:
;     None.
_userBSSInit:
    xor rax, rax
    mov r8, _USER_START_BSS_ADDR
    mov r9, _USER_END_BSS_ADDR

_initBSSLoop:
    cmp r8, r9
    je _initBSSEnd
    mov [r8], al
    inc r8
    jmp _initBSSLoop

_initBSSEnd:
    ret
;-------------------------------------------------------------------------------
; DATA
;-------------------------------------------------------------------------------

section .data
; None