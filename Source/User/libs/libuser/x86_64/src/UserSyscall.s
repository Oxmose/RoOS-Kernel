;-------------------------------------------------------------------------------
; EXPORTED FUNCTIONS
;-------------------------------------------------------------------------------
global Syscall

;-------------------------------------------------------------------------------
; EXPORTED DATA
;-------------------------------------------------------------------------------
; None

;-------------------------------------------------------------------------------
; CODE
;-------------------------------------------------------------------------------
section .text
align 4

;-------------------------------------------------------------------------------
; Performs a system call request from the user space.
;
; Param:
;     RDI - The system call ID to handle.
;     RSI - The first parameter for the system call.
;     RDX - The second parameter for the system call.
;     RCX - The third parameter for the system call.
;     R8  - The fourth parameter for the system call.
;     R9  - The fifth parameter for the system call.
; Return: RAX: The result of the system call.
Syscall:
    ; Move RCX to R10 as syscall will overwrite it
    mov r10, rcx
    ; Perform the system call
    syscall
    ret

;-------------------------------------------------------------------------------
; DATA
;-------------------------------------------------------------------------------
section .data
; None